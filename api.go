// Package rstgo is a native Go implementation of Docutils' reStructuredText
// to HTML conversion (rst2html / rst2html5), aiming at byte-for-byte
// compatible output.
//
// The pipeline mirrors Docutils: parser -> document tree (node types as in
// docutils.nodes) -> transforms -> writer.
package rstgo

import (
	"fmt"
	"io"
)

// Writer selects the output format.
type Writer int

const (
	// HTML4 is Docutils' "html4css1" writer (XHTML 1.0 Transitional), the
	// writer used by the rst2html command.
	HTML4 Writer = iota
	// HTML5 is Docutils' "html5_polyglot" writer (rst2html5).
	HTML5
)

// Options holds the conversion settings.  The zero value corresponds to the
// Docutils defaults; use the fields to deviate from them.
type Options struct {
	// Writer selects the HTML flavour (default HTML4, like rst2html).
	Writer Writer
	// SourcePath is the path of the input (used in system messages, for
	// resolving "include" and friends and for the source link).  Empty
	// means standard input ("<stdin>").
	SourcePath string
	// DestPath is the output path (used to compute relative stylesheet and
	// source-link paths).  Empty means standard output.
	DestPath string
	// Stderr receives system messages (warnings and errors), formatted like
	// Docutils does.  Nil discards them.
	Stderr io.Writer

	// InitialHeaderLevel is the level of the first section header (default:
	// 1 for HTML4, 2 for HTML5).
	InitialHeaderLevel int
	// NoDocTitle disables promotion of a lone top-level section title to the
	// document title (--no-doc-title).
	NoDocTitle bool
	// NoDocInfo disables the bibliographic field list transform.
	NoDocInfo bool
	// SectionSubtitles enables promotion of lone subsection titles.
	SectionSubtitles bool
	// Title sets the document title metadata (--title).
	Title string

	// Stylesheet is a list of stylesheet URLs/references (--stylesheet); the
	// references are used verbatim.  Mutually exclusive with StylesheetPath.
	Stylesheet []string
	// StylesheetPath is a list of stylesheet file paths (--stylesheet-path).
	// Names that are not found relative to the working directory are looked
	// up among the stylesheets bundled with Docutils.  If both Stylesheet
	// and StylesheetPath are empty the writer's default stylesheets are used.
	StylesheetPath []string
	// NoStylesheet suppresses the default stylesheet (like --stylesheet="").
	NoStylesheet bool
	// LinkStylesheet links to the stylesheets instead of embedding them.
	LinkStylesheet bool

	// ReportLevel is the minimum level of system messages that are reported
	// (1 info, 2 warning (default), 3 error, 4 severe, 5 none).
	ReportLevel int
	// HaltLevel is the level at which processing is aborted (default 4).
	HaltLevel int
	// NoFileInsertion disables "include", "raw :file:" and "csv-table :file:".
	NoFileInsertion bool
	// NoRaw disables the "raw" directive and role.
	NoRaw bool
	// TabWidth is the tab expansion width (default 8).
	TabWidth int
	// LineLengthLimit is the maximum input line length (default 10000).
	LineLengthLimit int

	// Generator adds a "Generated by Docutils" footer (--generator).
	Generator bool
	// Datestamp is a strftime format for a "Generated on" footer line
	// (--date: "%Y-%m-%d", --time: "%Y-%m-%d %H:%M UTC").
	Datestamp string
	// SourceLink adds a "View document source" link; SourceURL overrides
	// the link target.
	SourceLink bool
	SourceURL  string

	// TocBacklinks is "entry" (default), "top" or "none".
	TocBacklinks string
	// NoFootnoteBacklinks disables links from footnotes back to references.
	NoFootnoteBacklinks bool
	// NoSectionNumbering disables the "sectnum" directive.
	NoSectionNumbering bool
	// StripComments removes comments from the document tree.
	StripComments bool
	// StripClasses / StripElementsWithClasses mirror --strip-class and
	// --strip-elements-with-class.
	StripClasses             []string
	StripElementsWithClasses []string

	// TrimFootnoteReferenceSpace: nil = writer default.
	TrimFootnoteReferenceSpace *bool
	// FootnoteReferences is "superscript" or "brackets" (default depends on
	// the writer).
	FootnoteReferences string
	// PEPReferences / RFCReferences enable recognition of standalone
	// "PEP 8" / "RFC 2822" references.
	PEPReferences bool
	RFCReferences bool
	// SyntaxHighlight is "long" (default), "short" or "none".
	SyntaxHighlight string
	// CharacterLevelInlineMarkup enables the experimental setting of the
	// same name.
	CharacterLevelInlineMarkup bool
	// MathOutput selects the math rendering ("" = writer default); see the
	// README for supported values.
	MathOutput string
	// NoXMLDeclaration omits the XML declaration (HTML4: on by default).
	NoXMLDeclaration bool
	// XMLDeclaration forces an XML declaration (HTML5: off by default).
	XMLDeclaration bool
	// NoCompactLists / NoCompactFieldLists disable list compaction.
	NoCompactLists      bool
	NoCompactFieldLists bool
	// TableStyle is the --table-style value.
	TableStyle string
	// Attribution is "dash" (default), "parentheses"/"parens" or "none".
	Attribution string
	// CloakEmailAddresses scrambles e-mail addresses.
	CloakEmailAddresses bool
	// FieldNameLimit and OptionLimit (HTML4 only; defaults 14; 0 means the
	// default, a negative value disables the limit).
	FieldNameLimit int
	OptionLimit    int
	// SectionSelfLink adds self-links to section headings (HTML5).
	SectionSelfLink bool
	// ImageLoading is "link" (default), "embed" or "lazy" (HTML5).
	ImageLoading string
	// RootPrefix is the base directory for absolute include paths.
	RootPrefix string
}

func (o *Options) settings() *settings {
	st := &settings{
		generator: o.Generator, datestamp: o.Datestamp, sourceLink: o.SourceLink,
		sourceURL: o.SourceURL, title: o.Title,
		tocBacklinks: "entry", footnoteBackl: !o.NoFootnoteBacklinks,
		sectnumXform: !o.NoSectionNumbering, stripComments: o.StripComments,
		stripClasses: o.StripClasses, stripElemsClass: o.StripElementsWithClasses,
		reportLevel: 2, haltLevel: 4, languageCode: "en", autoIDPrefix: "%",
		legacyIDs: true, fileInsertionEnabled: !o.NoFileInsertion,
		rawEnabled: !o.NoRaw, lineLengthLimit: 10000, pepReferences: o.PEPReferences,
		pepBaseURL: "https://peps.python.org/", pepFileURLTemplate: "pep-%04d",
		rfcReferences: o.RFCReferences, rfcBaseURL: "https://tools.ietf.org/html/",
		tabWidth: 8, trimFootnoteReferenceSpace: o.TrimFootnoteReferenceSpace,
		syntaxHighlight: "long", characterLevelInlineMarkup: o.CharacterLevelInlineMarkup,
		rootPrefix: o.RootPrefix, doctitleXform: !o.NoDocTitle, docinfoXform: !o.NoDocInfo,
		sectsubtitleXform: o.SectionSubtitles, embedStylesheet: !o.LinkStylesheet,
		compactLists: !o.NoCompactLists, compactFieldLists: !o.NoCompactFieldLists,
		tableStyle: o.TableStyle, attribution: "dash", cloakEmailAddresses: o.CloakEmailAddresses,
		fieldNameLimit: 14, optionLimit: 14, sectionSelfLink: o.SectionSelfLink,
		imageLoading: "link", outputEncoding: "utf-8", sourcePath: o.SourcePath,
		destPath: o.DestPath, hasSource: o.SourcePath != "", mathOutput: o.MathOutput,
	}
	if o.Writer == HTML5 {
		st.writer = "html5"
		st.initialHeaderLevel = 2
		st.footnoteReferences = "brackets"
		st.xmlDeclaration = o.XMLDeclaration
		if st.mathOutput == "" {
			st.mathOutput = "MathML"
		}
	} else {
		st.writer = "html4"
		st.initialHeaderLevel = 1
		st.footnoteReferences = "brackets"
		st.xmlDeclaration = !o.NoXMLDeclaration
		if st.mathOutput == "" {
			st.mathOutput = "HTML math.css"
		}
	}
	if o.InitialHeaderLevel != 0 {
		st.initialHeaderLevel = o.InitialHeaderLevel
	}
	if o.ReportLevel != 0 {
		st.reportLevel = o.ReportLevel
	}
	if o.HaltLevel != 0 {
		st.haltLevel = o.HaltLevel
	}
	if o.TabWidth != 0 {
		st.tabWidth = o.TabWidth
	}
	if o.LineLengthLimit != 0 {
		st.lineLengthLimit = o.LineLengthLimit
	}
	switch o.TocBacklinks {
	case "top":
		st.tocBacklinks = "top"
	case "none":
		st.tocBacklinks = ""
	}
	if o.FootnoteReferences != "" {
		st.footnoteReferences = o.FootnoteReferences
	}
	if o.SyntaxHighlight != "" {
		st.syntaxHighlight = o.SyntaxHighlight
	}
	if o.Attribution != "" {
		st.attribution = o.Attribution
	}
	if o.FieldNameLimit != 0 {
		st.fieldNameLimit = o.FieldNameLimit
	}
	if o.OptionLimit != 0 {
		st.optionLimit = o.OptionLimit
	}
	if o.ImageLoading != "" {
		st.imageLoading = o.ImageLoading
	}
	st.stylesheets, st.stylesheetIsPath = o.Stylesheet, false
	if len(o.StylesheetPath) > 0 {
		st.stylesheets, st.stylesheetIsPath = o.StylesheetPath, true
	} else if len(o.Stylesheet) == 0 && !o.NoStylesheet {
		st.stylesheetIsPath = true
		if o.Writer == HTML5 {
			st.stylesheets = []string{"minimal.css", "plain.css"}
		} else {
			st.stylesheets = []string{"html4css1.css"}
		}
	}
	return st
}

func sourceName(o *Options) string {
	if o.SourcePath == "" {
		return "<stdin>"
	}
	return o.SourcePath
}

// catchHalt converts the internal "halt" panic into an error.
func catchHalt(err *error) {
	if r := recover(); r != nil {
		if h, ok := r.(*haltError); ok {
			*err = h
			return
		}
		panic(r)
	}
}

func parseDocument(src []byte, opts *Options, htmlWriter bool) (doc *Document, err error) {
	defer catchHalt(&err)
	st := opts.settings()
	text, derr := decodeInput(src, "utf-8")
	if derr != nil {
		return nil, fmt.Errorf("rstgo: input is not valid UTF-8")
	}
	doc = newDocument(sourceName(opts), st, opts.Stderr)
	parseInto(doc, text)
	applyStandardTransforms(doc, htmlWriter)
	return doc, nil
}

// Parse parses src and applies the standard transforms, returning the
// document tree as the pseudo-XML writer (rst2pseudoxml) would see it.
func Parse(src []byte, opts Options) (*Document, error) {
	return parseDocument(src, &opts, false)
}

// PseudoXML converts src to Docutils' pseudo-XML representation of the
// document tree (like rst2pseudoxml).
func PseudoXML(src []byte, opts Options) ([]byte, error) {
	doc, err := Parse(src, opts)
	if err != nil {
		return nil, err
	}
	return []byte(doc.PseudoXML()), nil
}

// Result carries information about a conversion run.
type Result struct {
	// MaxLevel is the highest system message level encountered (-1: none;
	// 1 info, 2 warning, 3 error, 4 severe).
	MaxLevel int
}

// PseudoXMLResult is like PseudoXML but also returns run information.
func PseudoXMLResult(src []byte, opts Options) ([]byte, Result, error) {
	doc, err := Parse(src, opts)
	if err != nil {
		return nil, Result{}, err
	}
	return []byte(doc.PseudoXML()), Result{MaxLevel: doc.reporter.maxLevel}, nil
}

// ConvertResult is like Convert but also returns run information.
func ConvertResult(src []byte, opts Options) ([]byte, Result, error) {
	return nil, Result{}, fmt.Errorf("not implemented")
}

// Convert converts reStructuredText to a complete HTML document.
func Convert(src []byte, opts Options) ([]byte, error) {
	out, _, err := ConvertResult(src, opts)
	return out, err
}
