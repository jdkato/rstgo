func xClassAttribute(d *Document, pending *Node) {
	classes, _ := pending.pend().details["class"].([]string)
	// findall(include_self=False, descend=False, siblings=True, ascend=True)
	node := pending
	for node.Parent != nil {
		idx := node.Parent.index(node)
		for _, element := range node.Parent.Children[idx+1:] {
			if element.IsText() {
				// Text nodes have no classes; Docutils would fail here.
				continue
			}
			if invisibleTags[element.Tag] || element.Tag == "system_message" {
				continue
			}
			element.appendTo("classes", classes...)
			pending.Parent.remove(pending)
			return
		}
		node = node.Parent
	}
	e := d.reporter.error(fmt.Sprintf(`No suitable element following "%s" directive`, pending.pend().details["directive"]),
		[]*Node{newTextElem("literal_block", pending.Rawsource, pending.Rawsource)}, atLine(pending.Line))
	pending.replaceSelf(e)
}

var transitionIgnored = set("decoration meta pending substitution_definition subtitle target title")

// bodyParents lists the elements whose content model includes Body
// elements (and therefore system messages).
var bodyParents = set(`admonition attention block_quote caution citation compound
	container danger definition description document entry error field_body
	footer footnote header hint important legend list_item note section sidebar
	system_message tip topic warning`)

func xTransitions(d *Document, _ *Node) {
	for _, node := range d.Root.findTag("transition") {
		warn := func(msg string) {
			w := d.reporter.warning(msg, nil, baseNode(node))
			if bodyParents[node.Parent.Tag] {
				node.Parent.insert(node.Parent.index(node)+1, w)
			}
		}
		var follows, begins, ends bool
		if !node.Parent.is("document", "section") {
			warn("Transition only valid as child of <document> or <section>.")
		} else {
			if ps := node.previousSibling(); ps != nil && ps.Tag == "transition" {
				follows = true
			}
			i := node.Parent.index(node)
			begins, ends = true, true
			for _, sib := range node.Parent.Children[:i] {
				if !transitionIgnored[sib.Tag] {
					begins = false
				}
			}
			for _, sib := range node.Parent.Children[i+1:] {
				if !transitionIgnored[sib.Tag] {
					ends = false
				}
			}
		}
		if ends {
			sibling := node.Parent
			parent := sibling.Parent
			moved := false
			for parent != nil {
				index := parent.index(sibling)
				if index < len(parent.Children)-1 {
					node.Parent.remove(node)
					parent.insert(index+1, node)
					moved = true
					break
				}
				sibling = sibling.Parent
				parent = sibling.Parent
			}
			if !moved {
				warn("Transition at the end of the document.")
			}
		}
		if begins {
			warn(fmt.Sprintf("Transition at the start of the %s.", node.Parent.Tag))
		} else if follows {
			warn("At least one body element should separate transitions.")
		}
	}
}

func xSmartQuotes(d *Document, _ *Node) {
	if d.settings.smartQuotes == "" {
		return
	}
	applySmartQuotes(d)
}

