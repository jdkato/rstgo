package rstgo

// Ports of docutils.transforms.* as applied by the standalone reader, the
// reStructuredText parser and the HTML / pseudo-XML writers.

import (
	"fmt"
	"sort"
	"strings"
	"time"
)

type transformFn func(d *Document, startnode *Node)

type xform struct {
	priority int
	serial   int
	fn       transformFn
	pending  *Node
}

var pendingTransforms = map[string]struct {
	priority int
	fn       transformFn
}{
	"docutils.transforms.parts.SectNum":          {710, xSectNum},
	"docutils.transforms.parts.Contents":         {720, xContents},
	"docutils.transforms.references.TargetNotes": {540, xTargetNotes},
	"docutils.transforms.misc.ClassAttribute":    {210, xClassAttribute},
}

func (d *Document) drainPendings(list []xform) []xform {
	for _, p := range d.pendings {
		t := pendingTransforms[p.node.pend().transform]
		pr := t.priority
		if p.priority != 0 {
			pr = p.priority
		}
		list = append(list, xform{pr, p.serial, t.fn, p.node})
	}
	d.pendings = nil
	return list
}

func (d *Document) runTransforms(component [][2]any) {
	var list []xform
	list = d.drainPendings(list)
	for _, c := range component {
		d.serial++
		list = append(list, xform{c[0].(int), d.serial, c[1].(func(*Document, *Node)), nil})
	}
	old := d.reporter.observer
	d.reporter.observer = func(m *Node) { d.transformMessages = append(d.transformMessages, m) }
	for len(list) > 0 {
		sort.SliceStable(list, func(i, j int) bool {
			if list[i].priority != list[j].priority {
				return list[i].priority < list[j].priority
			}
			return list[i].serial < list[j].serial
		})
		x := list[0]
		list = list[1:]
		x.fn(d, x.pending)
		list = d.drainPendings(list)
	}
	d.reporter.observer = old
}

func tf(priority int, fn func(*Document, *Node)) [2]any { return [2]any{priority, fn} }

// applyStandardTransforms applies reader + parser + writer transforms.
func applyStandardTransforms(d *Document, htmlWriter bool) {
	comps := [][2]any{
		// readers.Reader
		tf(820, xDecorations), tf(740, xStripComments),
		// readers.standalone
		tf(220, xSubstitutions), tf(260, xPropagateTargets), tf(320, xDocTitle),
		tf(350, xSectionSubTitle), tf(340, xDocInfo), tf(440, xAnonymousHyperlinks),
		tf(460, xIndirectHyperlinks), tf(620, xFootnotes), tf(640, xExternalTargets),
		tf(660, xInternalTargets), tf(850, xDanglingReferences), tf(830, xTransitions),
		// parser: Validate (no-op), SmartQuotes
		tf(855, xSmartQuotes),
		// writers.Writer
		tf(860, xMessages), tf(870, xFilterMessages), tf(420, xStripClassesAndElements),
	}
	if htmlWriter {
		comps = append(comps, tf(920, xAdmonitions))
	}
	d.runTransforms(comps)
}

// applyParserTransforms is used for documents parsed by "include" with a
// custom parser.
func applyParserTransforms(d *Document) {
	d.runTransforms([][2]any{tf(855, xSmartQuotes)})
}

func (d *Document) problematicFor(ref *Node, msgid string) *Node {
	prb := newTextElem("problematic", ref.Rawsource, ref.Rawsource)
	prb.setAttr("refid", msgid)
	return prb
}

