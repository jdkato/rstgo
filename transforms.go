func xDecorations(d *Document, _ *Node) {
	st := d.settings
	if !(st.generator || st.datestamp != "" || st.sourceLink || st.sourceURL != "") {
		return
	}
	var text []*Node
	if (st.sourceLink && st.hasSource) || st.sourceURL != "" {
		source := st.sourceURL
		if source == "" {
			source = relativePathFrom(st.destPath, st.sourcePath)
		}
		ref := newTextElem("reference", "", "View document source")
		ref.setAttr("refuri", source)
		text = append(text, ref, newText(".\n"))
	}
	if st.datestamp != "" {
		text = append(text, newText("Generated on: "+strftime(st.datestamp, time.Now().UTC())+".\n"))
	}
	if st.generator {
		r1 := newTextElem("reference", "", "Docutils")
		r1.setAttr("refuri", "https://docutils.sourceforge.io/")
		r2 := newTextElem("reference", "", "reStructuredText")
		r2.setAttr("refuri", "https://docutils.sourceforge.io/rst.html")
		text = append(text, newText("Generated by "), r1, newText(" from "), r2, newText(" source.\n"))
	}
	footer := decorationFooter(d.getDecoration())
	footer.append(newTextElem("paragraph", "", "", text...))
}

func xStripComments(d *Document, _ *Node) {
	if d.settings.stripComments {
		for _, n := range d.Root.findTag("comment") {
			n.Parent.remove(n)
		}
	}
}

func xMessages(d *Document, _ *Node) {
	var loose []*Node
	for _, m := range d.parseMessages {
		if m.Parent == nil {
			loose = append(loose, m)
		}
	}
	for _, m := range d.transformMessages {
		if m.Parent == nil {
			loose = append(loose, m)
		}
	}
	if len(loose) > 0 {
		section := newElem("section", "")
		section.appendTo("classes", "system-messages")
		section.append(newTextElem("title", "", "Docutils System Messages"))
		section.extend(loose)
		d.transformMessages = nil
		d.Root.append(section)
	}
}

func xFilterMessages(d *Document, _ *Node) {
	removed := map[string]bool{}
	for _, n := range d.Root.findTag("system_message") {
		if lv, _ := n.get("level").(int); lv < d.reporter.reportLevel {
			n.Parent.remove(n)
			for _, id := range n.list("ids") {
				delete(d.ids, id)
				removed[id] = true
			}
		}
	}
	for _, n := range d.Root.findTag("problematic") {
		if n.has("refid") && removed[n.str("refid")] {
			n.Parent.replace(n, newText(n.astext()))
		}
	}
	for _, n := range d.Root.findTag("section") {
		if containsStr(n.list("classes"), "system-messages") && len(n.Children) == 1 && n.Parent != nil {
			n.Parent.remove(n)
		}
	}
}

func xStripClassesAndElements(d *Document, _ *Node) {
	st := d.settings
	if len(st.stripElemsClass) > 0 {
		for _, n := range d.Root.findall(func(n *Node) bool {
			if n.IsText() {
				return false
			}
			for _, c := range n.list("classes") {
				if containsStr(st.stripElemsClass, c) {
					return true
				}
			}
			return false
		}) {
			if n.Parent != nil {
				n.Parent.remove(n)
			}
		}
	}
	if len(st.stripClasses) == 0 {
		return
	}
	for _, n := range d.Root.findall(func(n *Node) bool { return !n.IsText() }) {
		for _, c := range st.stripClasses {
			n.removeFrom("classes", c)
		}
	}
}

var admonitionLabels = map[string]string{
	"attention": "Attention!", "caution": "Caution!", "danger": "!DANGER!",
	"error": "Error", "hint": "Hint", "important": "Important", "note": "Note",
	"tip": "Tip", "warning": "Warning",
}

func xAdmonitions(d *Document, _ *Node) {
	for _, node := range d.Root.findall(func(n *Node) bool { return admonitionTags[n.Tag] }) {
		name := node.Tag
		node.appendTo("classes", name)
		if name != "admonition" {
			adm := newElem("admonition", node.Rawsource, node.Children...)
			for k, v := range node.Attrs {
				if l, ok := v.([]string); ok {
					adm.setAttr(k, append([]string{}, l...))
				} else {
					adm.setAttr(k, v)
				}
			}
			adm.insert(0, newTextElem("title", "", admonitionLabels[name]))
			node.replaceSelf(adm)
		}
	}
}

