func xSectNum(d *Document, start *Node) {
	det := start.pend().details
	maxdepth := int(^uint(0) >> 1)
	if v, ok := det["depth"].(int); ok {
		maxdepth = v
	}
	startvalue := 1
	if v, ok := det["start"].(int); ok {
		startvalue = v
	}
	prefix, _ := det["prefix"].(string)
	suffix, _ := det["suffix"].(string)
	start.Parent.remove(start)
	if !d.settings.sectnumXform {
		return
	}
	var update func(node *Node, numbers []string, depth int)
	update = func(node *Node, pfx []string, depth int) {
		depth++
		sectnum := startvalue
		if len(pfx) > 0 {
			sectnum = 1
		}
		for _, child := range append([]*Node{}, node.Children...) {
			if child.Tag == "section" {
				numbers := append(append([]string{}, pfx...), fmt.Sprint(sectnum))
				title := child.Children[0]
				gen := newTextElem("generated", "", prefix+strings.Join(numbers, ".")+suffix+"   ")
				gen.appendTo("classes", "sectnum")
				title.insert(0, gen)
				title.setAttr("auto", 1)
				if depth < maxdepth {
					update(child, numbers, depth)
				}
				sectnum++
			}
		}
	}
	update(d.Root, nil, 0)
}

func xContents(d *Document, start *Node) {
	tocID := d.setID(start.Parent, nil, "")
	det := start.pend().details
	var startnode *Node
	if _, ok := det["local"]; ok {
		startnode = start.Parent.Parent
		for !startnode.is("section", "document") {
			startnode = startnode.Parent
		}
	} else {
		startnode = d.Root
	}
	backlinks := d.settings.tocBacklinks
	if v, ok := det["backlinks"]; ok {
		backlinks, _ = v.(string)
	}
	depth := int(^uint(0) >> 1)
	if v, ok := det["depth"].(int); ok {
		depth = v
	}
	var build func(node *Node, level int) *Node
	build = func(node *Node, level int) *Node {
		level++
		var entries []*Node
		auto := false
		for _, section := range node.Children {
			if section.Tag != "section" {
				continue
			}
			title := section.Children[0]
			auto = title.truthy("auto")
			entrytext := copyAndFilter(title)
			reference := newTextElem("reference", "", "", entrytext...)
			reference.setAttr("refid", section.list("ids")[0])
			refID := d.setID(reference, nil, "toc-entry")
			entry := newTextElem("paragraph", "", "", reference)
			item := newElem("list_item", "", entry)
			if (backlinks == "entry" || backlinks == "top") &&
				title.nextNode(func(n *Node) bool { return n.Tag == "reference" }, true, false, false) == nil {
				if backlinks == "entry" {
					title.setAttr("refid", refID)
				} else {
					title.setAttr("refid", tocID)
				}
			}
			if level < depth {
				if sub := build(section, level); sub != nil {
					item.append(sub)
				}
			}
			entries = append(entries, item)
		}
		if len(entries) > 0 {
			contents := newElem("bullet_list", "", entries...)
			if auto {
				contents.appendTo("classes", "auto-toc")
			}
			return contents
		}
		return nil
	}
	contents := build(startnode, 0)
	if contents != nil {
		start.replaceSelf(contents)
	} else {
		start.Parent.Parent.remove(start.Parent)
	}
}

// copyAndFilter mirrors parts.ContentsFilter applied to a title node.
func copyAndFilter(title *Node) []*Node {
	var walk func(n *Node, parent *Node)
	walk = func(n *Node, parent *Node) {
		switch n.Tag {
		case "citation_reference", "footnote_reference":
			return
		case "image":
			if n.has("alt") {
				parent.append(newText(n.str("alt")))
			}
			return
		case "problematic", "reference", "target":
			for _, c := range n.Children {
				walk(c, parent)
			}
			return
		}
		c := n.copyNode()
		parent.Children = append(parent.Children, c)
		c.Parent = parent
		for _, ch := range n.Children {
			walk(ch, c)
		}
	}
	root := newElem("Element", "")
	walk(title, root)
	out := root.Children[0].Children
	for _, c := range out {
		c.Parent = nil
	}
	return out
}

// ---------------------------------------------------------------- frontmatter

func isPreBibliographic(n *Node) bool { return preBibliographicTag[n.Tag] }

func candidateIndex(node *Node) (*Node, int) {
	index := node.firstChildNotMatching(isPreBibliographic)
	if index < 0 || len(node.Children) > index+1 || node.Children[index].Tag != "section" {
		return nil, -1
	}
	return node.Children[index], index
}

// updateAllAttsConcatenating mirrors Element.update_all_atts_concatenating
// (replace=True, and_source=True).
func (n *Node) updateAllAttsConcatenating(from *Node) {
	n.updateBasicAtts(from)
	for k, v := range from.Attrs {
		switch k {
		case "ids", "classes", "names", "dupnames":
			continue
		}
		if l, ok := v.([]string); ok {
			if _, ok2 := n.Attrs[k].([]string); ok2 {
				for _, x := range l {
					n.appendUnique(k, x)
				}
				continue
			}
			n.setAttr(k, append([]string{}, l...))
			continue
		}
		n.setAttr(k, v)
	}
}

func (n *Node) setChildren(cs []*Node) {
	n.Children = nil
	for _, c := range cs {
		n.append(c)
	}
}

func promoteTitle(node *Node) bool {
	section, index := candidateIndex(node)
	if section == nil {
		return false
	}
	node.updateAllAttsConcatenating(section)
	var cs []*Node
	cs = append(cs, section.Children[:1]...)
	cs = append(cs, node.Children[:index]...)
	cs = append(cs, section.Children[1:]...)
	node.setChildren(cs)
	return true
}

func promoteSubtitle(node *Node) bool {
	subsection, index := candidateIndex(node)
	if subsection == nil {
		return false
	}
	subtitle := newElem("subtitle", "")
	subtitle.updateAllAttsConcatenating(subsection)
	subtitle.setChildren(subsection.Children[0].Children)
	var cs []*Node
	cs = append(cs, node.Children[:1]...)
	cs = append(cs, subtitle)
	cs = append(cs, node.Children[1:index]...)
	cs = append(cs, subsection.Children[1:]...)
	node.setChildren(cs)
	return true
}

func xDocTitle(d *Document, _ *Node) {
	if d.settings.doctitleXform {
		if promoteTitle(d.Root) {
			promoteSubtitle(d.Root)
		}
	}
	if !d.Root.has("title") {
		if d.settings.title != "" {
			d.Root.setAttr("title", d.settings.title)
		} else if len(d.Root.Children) > 0 && d.Root.Children[0].Tag == "title" {
			d.Root.setAttr("title", d.Root.Children[0].astext())
		}
	}
}

func xSectionSubTitle(d *Document, _ *Node) {
	if !d.settings.sectsubtitleXform {
		return
	}
	for _, section := range d.Root.findTag("section") {
		promoteSubtitle(section)
	}
}

var bibliographicFields = set(`author authors organization address contact
	version revision status date copyright dedication abstract`)

var biblioLabels = map[string]string{"dedication": "Dedication", "abstract": "Abstract"}

func cleanRCSKeywords(paragraph *Node) {
	if len(paragraph.Children) == 1 && paragraph.Children[0].IsText() {
		textnode := paragraph.Children[0]
		for n := 0; n < 3; n++ {
			if text, ok := rcsKeywordSub(n, textnode.Text); ok {
				paragraph.Children[0] = newText(text)
				paragraph.setupChild(paragraph.Children[0])
				return
			}
		}
	}
}

func xDocInfo(d *Document, _ *Node) {
	if !d.settings.docinfoXform {
		return
	}
	root := d.Root
	index := root.firstChildNotMatching(isPreBibliographic)
	if index < 0 {
		return
	}
	candidate := root.Children[index]
	if candidate.Tag == "field_list" {
		biblioindex := root.firstChildNotMatching(func(n *Node) bool {
			return n.isTitular() || n.is("decoration", "meta")
		})
		nodelist := d.extractBibliographic(candidate)
		root.removeAt(index)
		if biblioindex < 0 {
			biblioindex = len(root.Children)
		}
		root.insertAll(biblioindex, nodelist)
	}
}

func (d *Document) extractBibliographic(fieldList *Node) []*Node {
	docinfo := newElem("docinfo", "")
	topics := map[string]*Node{}
	for _, field := range append([]*Node{}, fieldList.Children...) {
		name := ""
		if len(field.Children[0].Children) > 0 {
			name = field.Children[0].Children[0].astext()
		}
		normedname := fullyNormalizeName(name)
		ok := func() bool {
			if len(field.Children[0].Children) == 0 {
				return false
			}
			if !(len(field.Children) == 2 && bibliographicFields[normedname] && d.checkEmptyBiblioField(field, name)) {
				return false
			}
			canonical := normedname
			body := field.Children[1]
			switch canonical {
			case "authors":
				return d.extractAuthors(field, name, docinfo)
			case "dedication", "abstract":
				if topics[canonical] != nil {
					body.append(d.reporter.warning(fmt.Sprintf(`There can only be one "%s" field.`, name), nil, baseNode(field)))
					return false
				}
				title := newTextElem("title", name, biblioLabels[canonical])
				title.Children[0].Rawsource = biblioLabels[canonical]
				topic := newElem("topic", "", title)
				topic.extend(body.Children)
				topic.appendTo("classes", canonical)
				topics[canonical] = topic
			default:
				if !d.checkCompoundBiblioField(field, name) {
					return false
				}
				cleanRCSKeywords(body.Children[0])
				docinfo.append(newTextElem(canonical, "", "", body.Children[0].Children...))
			}
			return true
		}()
		if !ok {
			last := field.Children[len(field.Children)-1]
			if len(last.Children) == 1 && last.Children[0].Tag == "paragraph" {
				cleanRCSKeywords(last.Children[0])
			}
			if cv := makeID(normedname); cv != "" {
				field.appendTo("classes", cv)
			}
			docinfo.append(field)
		}
	}
	var nodelist []*Node
	if len(docinfo.Children) > 0 {
		nodelist = append(nodelist, docinfo)
	}
	if t := topics["dedication"]; t != nil {
		nodelist = append(nodelist, t)
	}
	if t := topics["abstract"]; t != nil {
		nodelist = append(nodelist, t)
	}
	return nodelist
}

func (d *Document) checkEmptyBiblioField(field *Node, name string) bool {
	last := field.Children[len(field.Children)-1]
	if len(last.Children) < 1 {
		last.append(d.reporter.warning(fmt.Sprintf(`Cannot extract empty bibliographic field "%s".`, name), nil, baseNode(field)))
		return false
	}
	return true
}

func (d *Document) checkCompoundBiblioField(field *Node, name string) bool {
	fBody := field.Children[len(field.Children)-1]
	if len(fBody.Children) == 1 && fBody.Children[0].Tag == "paragraph" {
		return true
	}
	if fBody.Children[0].Tag == "enumerated_list" && !strings.Contains(pyStrip(fBody.Rawsource), "\n") {
		doc := newDocument("*DocInfo transform*", d.settings, d.reporter.stream)
		parseInto(doc, `\`+fBody.Rawsource)
		if len(doc.Root.Children) == 1 && doc.Root.Children[0].Tag == "paragraph" {
			fBody.Children = doc.Root.Children
			return true
		}
	}
	var content []string
	for _, e := range fBody.Children {
		if e.Tag != "system_message" {
			content = append(content, "<"+e.Tag+">")
		}
	}
	var cs string
	if len(content) > 1 {
		cs = "[" + strings.Join(content, ", ") + "]"
	} else if len(content) == 1 {
		cs = "a " + content[0]
	}
	fBody.append(d.reporter.warning(fmt.Sprintf("Bibliographic field \"%s\"\nmust contain a single <paragraph>, not %s.", name, cs),
		nil, baseNode(field)))
	return false
}

func (d *Document) extractAuthors(field *Node, name string, docinfo *Node) bool {
	body := field.Children[1]
	var authors [][]*Node
	ok := true
	if len(body.Children) == 1 {
		switch body.Children[0].Tag {
		case "paragraph":
			authors, ok = authorsFromOneParagraph(field)
		case "bullet_list":
			for _, item := range body.Children[0].Children {
				if item.Tag == "comment" {
					continue
				}
				if len(item.Children) != 1 || item.Children[0].Tag != "paragraph" {
					ok = false
					break
				}
				authors = append(authors, item.Children[0].Children)
			}
			if len(authors) == 0 {
				ok = false
			}
		default:
			ok = false
		}
	} else {
		for _, item := range body.Children {
			if !item.is("paragraph", "comment") {
				ok = false
			}
		}
		if ok {
			for _, item := range body.Children {
				if item.Tag != "comment" {
					authors = append(authors, item.Children)
				}
			}
		}
	}
	if ok {
		var authornodes []*Node
		for _, a := range authors {
			if len(a) > 0 {
				authornodes = append(authornodes, newTextElem("author", "", "", a...))
			}
		}
		if len(authornodes) >= 1 {
			docinfo.append(newElem("authors", "", authornodes...))
			return true
		}
	}
	field.Children[len(field.Children)-1].append(d.reporter.warning(
		fmt.Sprintf("Cannot extract \"%s\" from bibliographic field:\n"+
			"Bibliographic field \"%s\" must contain either\n"+
			" a single paragraph (with author names separated by a"+
			" character from the set \";,\"),\n"+
			" multiple paragraphs (one per author),\n"+
			" or a bullet list with one author name per item.\n"+
			"Note: Leading initials can cause (mis)recognizing names "+
			"as enumerated list.", name, name), nil, baseNode(field)))
	return false
}

func authorsFromOneParagraph(field *Node) ([][]*Node, bool) {
	var sb strings.Builder
	for _, t := range field.Children[1].findall(func(n *Node) bool { return n.IsText() }) {
		sb.WriteString(t.Text)
	}
	text := sb.String()
	if text == "" {
		return nil, false
	}
	var names []string
	for _, sep := range []byte{';', ','} {
		names = splitUnescaped(text, sep)
		if len(names) > 1 {
			break
		}
	}
	var out [][]*Node
	for _, n := range names {
		n = pyStrip(n)
		if n != "" {
			out = append(out, []*Node{newText(n)})
		}
	}
	return out, true
}
