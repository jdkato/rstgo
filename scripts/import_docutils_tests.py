#!/usr/bin/env python3
"""Extract the reStructuredText inputs of Docutils' own parser/transform
unit tests (the ``totest`` tables in test/test_parsers/test_rst/**.py and
test/test_transforms/*.py of a Docutils source distribution) into
testdata/suites/<module>.json.

Usage: python3 -I scripts/import_docutils_tests.py /path/to/docutils-0.23

The test modules are *not* executed: they are parsed with ``ast`` and only
string literals are evaluated.  Only the inputs are taken from Docutils; the
expected outputs are generated by scripts/regen.py with the installed
Docutils.
"""
import ast
import json
import os
import sys

root = sys.argv[1]
out_dir = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                       '..', 'testdata', 'suites')
dirs = ['test/test_parsers/test_rst',
        'test/test_parsers/test_rst/test_directives',
        'test/test_transforms',
        'test/test_readers/test_standalone']


def const_str(node):
    """Return the value of a (possibly concatenated) string literal."""
    try:
        value = ast.literal_eval(node)
    except Exception:
        return None
    return value if isinstance(value, str) else None


def inputs(node):
    """Yield the first string of every [input, expected] pair below node."""
    if isinstance(node, (ast.List, ast.Tuple)):
        elts = node.elts
        if elts and const_str(elts[0]) is not None and len(elts) >= 2:
            yield const_str(elts[0])
            return
        for e in elts:
            yield from inputs(e)


total = 0
for d in dirs:
    full = os.path.join(root, d)
    if not os.path.isdir(full):
        continue
    for fn in sorted(os.listdir(full)):
        if not (fn.startswith('test_') and fn.endswith('.py')):
            continue
        with open(os.path.join(full, fn), encoding='utf-8') as f:
            tree = ast.parse(f.read())
        cases = []
        for stmt in ast.walk(tree):
            if not isinstance(stmt, ast.Assign) or len(stmt.targets) != 1:
                continue
            target = stmt.targets[0]
            if not (isinstance(target, ast.Subscript)
                    and isinstance(target.value, ast.Name)
                    and target.value.id == 'totest'):
                continue
            key = const_str(target.slice) or 'case'
            for i, text in enumerate(inputs(stmt.value)):
                cases.append({'name': '%s/%d' % (key, i), 'input': text})
        if not cases:
            continue
        name = os.path.basename(d).replace('test_', '') + '_' + fn[5:-3]
        with open(os.path.join(out_dir, name + '.json'), 'w',
                  encoding='utf-8') as f:
            json.dump({'origin': d + '/' + fn, 'cases': cases}, f,
                      indent=1, ensure_ascii=False)
            f.write('\n')
        total += len(cases)
        print(name, len(cases))
print('total', total)
