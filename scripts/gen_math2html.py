#!/usr/bin/env python3
"""Generate math2htmldata.go: the configuration tables of
docutils.utils.math.math2html (FormulaConfig), as built at import time
from the literal tables and docutils.utils.math.tex2unichar, and the
Unicode data its code relies on (str.isalpha, str.isdigit, NFC).

Run from the repository root:  python3 scripts/gen_math2html.py
"""
import json
import sys
import unicodedata
from docutils.utils.math import math2html

F = math2html.FormulaConfig


def q(s):
    return json.dumps(s, ensure_ascii=False)


out = ['// Code generated by scripts/gen_math2html.py from Docutils; DO NOT EDIT.',
       '', 'package rstgo', '']
for name in ('alphacommands', 'bracketcommands', 'combiningfunctions',
             'commands', 'oversetfunctions', 'undersetfunctions',
             'fontfunctions', 'hybridsizes', 'limitcommands', 'modified',
             'onefunctions', 'spacedcommands', 'symbolfunctions',
             'textfunctions'):
    d = getattr(F, name)
    out.append('var m2h%s = map[string]string{' % name.capitalize())
    for k in sorted(d):
        out.append('\t%s: %s,' % (q(k), q(d[k])))
    out.append('}')
    out.append('')
for name in ('bigbrackets', 'environments', 'hybridfunctions'):
    d = getattr(F, name)
    out.append('var m2h%s = map[string][]string{' % name.capitalize())
    for k in sorted(d):
        out.append('\t%s: {%s},' % (q(k), ', '.join(q(x) for x in d[k])))
    out.append('}')
    out.append('')
out.append('var m2hUnmodified = map[string]bool{')
for c in sorted(F.unmodified['characters']):
    out.append('\t%s: true,' % q(c))
out.append('}')
out.append('')


def ranges(pred):
    res = []
    start = None
    for cp in range(sys.maxunicode + 2):
        ok = cp <= sys.maxunicode and pred(chr(cp))
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            res.append((start, cp - 1))
            start = None
    return res


def emit_ranges(name, doc, pred):
    out.append('// %s' % doc)
    out.append('var %s = [][2]rune{' % name)
    for a, b in ranges(pred):
        out.append('\t{0x%x, 0x%x},' % (a, b))
    out.append('}')
    out.append('')


emit_ranges('pyAlphaRanges', 'pyAlphaRanges lists the characters for which str.isalpha() is true.',
            str.isalpha)
emit_ranges('pyStrDigitRanges', 'pyStrDigitRanges lists the characters for which str.isdigit() is true.',
            str.isdigit)

# Canonical decompositions (single level), combining classes and primary
# composites for NFC.
decomp = {}
comp = {}
ccc = {}
for cp in range(sys.maxunicode + 1):
    if 0xAC00 <= cp <= 0xD7A3:
        continue  # Hangul syllables are handled algorithmically
    ch = chr(cp)
    c = unicodedata.combining(ch)
    if c:
        ccc[cp] = c
    d = unicodedata.decomposition(ch)
    if d and not d.startswith('<'):
        parts = [int(x, 16) for x in d.split()]
        decomp[cp] = parts
        if len(parts) == 2 and unicodedata.normalize(
                'NFC', chr(parts[0]) + chr(parts[1])) == ch:
            comp[(parts[0], parts[1])] = cp
out.append('// nfcDecomp holds the canonical decomposition mappings (one level).')
out.append('var nfcDecomp = map[rune][]rune{')
for cp in sorted(decomp):
    out.append('\t0x%x: {%s},' % (cp, ', '.join('0x%x' % x for x in decomp[cp])))
out.append('}')
out.append('')
out.append('// nfcComp maps a (starter, mark) pair to its primary composite.')
out.append('var nfcComp = map[[2]rune]rune{')
for k in sorted(comp):
    out.append('\t{0x%x, 0x%x}: 0x%x,' % (k[0], k[1], comp[k]))
out.append('}')
out.append('')
out.append('// nfcClass holds the non-zero canonical combining classes.')
out.append('var nfcClass = map[rune]uint8{')
for cp in sorted(ccc):
    out.append('\t0x%x: %d,' % (cp, ccc[cp]))
out.append('}')
out.append('')
with open('math2htmldata.go', 'w', encoding='utf-8') as f:
    f.write('\n'.join(out))
