#!/usr/bin/env python3
"""Generate unidata.go from Python's unicodedata and Docutils' punctuation
tables.  Run from the repository root:  python3 scripts/gen_unidata.py"""
import sys
import unicodedata
from docutils.utils import punctuation_chars as pc
from docutils.utils import urischemes


def goq(s):
    out = []
    for ch in s:
        o = ord(ch)
        if ch in '\\"':
            out.append('\\' + ch)
        elif 32 <= o < 127:
            out.append(ch)
        elif o < 0x10000:
            out.append('\\u%04x' % o)
        else:
            out.append('\\U%08x' % o)
    return '"' + ''.join(out) + '"'


def ranges(pred):
    res = []
    start = None
    for cp in range(0x110000):
        if pred(chr(cp)):
            if start is None:
                start = cp
        elif start is not None:
            res.append((start, cp - 1))
            start = None
    if start is not None:
        res.append((start, 0x10ffff))
    return res


out = ['// Code generated by scripts/gen_unidata.py; DO NOT EDIT.',
       '', 'package rstgo', '',
       '// Data derived from the Unicode Character Database (Unicode %s)'
       % unicodedata.unidata_version,
       '// and from docutils/utils/punctuation_chars.py (public domain).', '']
for name in ('openers', 'closers', 'delimiters', 'closing_delimiters'):
    out.append('const punct_%s = %s' % (name, goq(getattr(pc, name))))
out.append('')
out.append('var quotePairs = map[rune]string{')
for k, v in sorted(pc.quote_pairs.items()):
    out.append('\t%s: %s,' % (hex(ord(k)), goq(v)))
out.append('}')
out.append('')
for name, pred in (('wideRanges',
                    lambda c: unicodedata.east_asian_width(c) in 'WF'),
                   ('combiningRanges',
                    lambda c: unicodedata.combining(c) != 0)):
    out.append('var %s = [][2]rune{' % name)
    line = []
    for a, b in ranges(pred):
        line.append('{0x%x, 0x%x}' % (a, b))
        if len(line) == 6:
            out.append('\t' + ', '.join(line) + ',')
            line = []
    if line:
        out.append('\t' + ', '.join(line) + ',')
    out.append('}')
    out.append('')
# NFKD -> ASCII folding used by make_id()
out.append('var nfkdASCII = map[rune]string{')
for cp in range(0x80, 0x110000):
    c = chr(cp)
    if 0xd800 <= cp <= 0xdfff:
        continue
    d = unicodedata.normalize('NFKD', c).encode('ascii', 'ignore').decode()
    if d:
        out.append('\t0x%x: %s,' % (cp, goq(d)))
out.append('}')
out.append('')
out.append('var uriSchemes = map[string]bool{')
for k in sorted(urischemes.schemes):
    out.append('\t%s: true,' % goq(k))
out.append('}')
open('unidata.go', 'w', encoding='utf-8').write('\n'.join(out) + '\n')
