#!/usr/bin/env python3
"""Generate unidata.go from Python's unicodedata and Docutils' punctuation
tables.  Run from the repository root:  python3 scripts/gen_unidata.py"""
import sys
import unicodedata
from docutils.utils import punctuation_chars as pc
from docutils.utils import urischemes


def goq(s):
    out = []
    for ch in s:
        o = ord(ch)
        if ch in '\\"':
            out.append('\\' + ch)
        elif 32 <= o < 127:
            out.append(ch)
        elif o < 0x10000:
            out.append('\\u%04x' % o)
        else:
            out.append('\\U%08x' % o)
    return '"' + ''.join(out) + '"'


def ranges(pred):
    res = []
    start = None
    for cp in range(0x110000):
        if pred(chr(cp)):
            if start is None:
                start = cp
        elif start is not None:
            res.append((start, cp - 1))
            start = None
    if start is not None:
        res.append((start, 0x10ffff))
    return res


out = ['// Code generated by scripts/gen_unidata.py; DO NOT EDIT.',
       '', 'package rstgo', '',
       '// Data derived from the Unicode Character Database (Unicode %s)'
       % unicodedata.unidata_version,
       '// and from docutils/utils/punctuation_chars.py (public domain).', '']
for name in ('openers', 'closers', 'delimiters', 'closing_delimiters'):
    out.append('const punct_%s = %s' % (name, goq(getattr(pc, name))))
out.append('')
out.append('var quotePairs = map[rune]string{')
for k, v in sorted(pc.quote_pairs.items()):
    out.append('\t%s: %s,' % (hex(ord(k)), goq(v)))
out.append('}')
out.append('')
for name, pred in (('wideRanges',
                    lambda c: unicodedata.east_asian_width(c) in 'WF'),
                   ('combiningRanges',
                    lambda c: unicodedata.combining(c) != 0)):
    out.append('var %s = [][2]rune{' % name)
    line = []
    for a, b in ranges(pred):
        line.append('{0x%x, 0x%x}' % (a, b))
        if len(line) == 6:
            out.append('\t' + ', '.join(line) + ',')
            line = []
    if line:
        out.append('\t' + ', '.join(line) + ',')
    out.append('}')
    out.append('')
# NFKD -> ASCII folding used by make_id()
out.append('var nfkdASCII = map[rune]string{')
for cp in range(0x80, 0x110000):
    c = chr(cp)
    if 0xd800 <= cp <= 0xdfff:
        continue
    d = unicodedata.normalize('NFKD', c).encode('ascii', 'ignore').decode()
    if d:
        out.append('\t0x%x: %s,' % (cp, goq(d)))
out.append('}')
out.append('')
out.append('var uriSchemes = map[string]bool{')
for k in sorted(urischemes.schemes):
    out.append('\t%s: true,' % goq(k))
out.append('}')
open('unidata.go', 'w', encoding='utf-8').write('\n'.join(out) + '\n')

# unichar2tex table used by the math roles/directives
from docutils.utils.math import unichar2tex  # noqa: E402
out = ['// Code generated by scripts/gen_unidata.py; DO NOT EDIT.',
       '', 'package rstgo', '',
       '// uni2tex maps Unicode characters to LaTeX math commands',
       '// (docutils/utils/math/unichar2tex.py, public domain).',
       'var uni2tex = map[rune]string{']
for k, v in sorted(unichar2tex.uni2tex_table.items()):
    out.append('\t0x%x: %s,' % (k, goq(v)))
out.append('}')
open('mathdata.go', 'w', encoding='utf-8').write('\n'.join(out) + '\n')

# tables for the LaTeX -> MathML conversion (html5 writer)
from docutils.utils.math import latex2mathml, mathalphabet2unichar  # noqa: E402
out = ['// Code generated by scripts/gen_unidata.py; DO NOT EDIT.',
       '', 'package rstgo', '',
       '// Symbol tables of docutils/utils/math/latex2mathml.py,',
       '// tex2unichar.py and mathalphabet2unichar.py (public domain / BSD).', '']
for name in ('letters', 'ordinary', 'operators', 'stretchables'):
    out.append('var mml_%s = map[string]string{' % name)
    for k, v in sorted(getattr(latex2mathml, name).items()):
        out.append('\t%s: %s,' % (goq(k), goq(v)))
    out.append('}')
    out.append('')
out.append('var mmlAlphabets = map[string]map[string]string{')
for name, table in sorted(vars(mathalphabet2unichar).items()):
    if not isinstance(table, dict) or name.startswith('_'):
        continue
    out.append('\t%s: {' % goq(name))
    for k, v in sorted(table.items()):
        out.append('\t\t%s: %s,' % (goq(k), goq(v)))
    out.append('\t},')
out.append('}')
out.append('')
out.append('// nfcNot maps a character to its precomposed form with U+0338')
out.append('// (COMBINING LONG SOLIDUS OVERLAY), where one exists.')
out.append('var nfcNot = map[rune]rune{')
for cp in range(0x20, 0x30000):
    if 0xd800 <= cp <= 0xdfff:
        continue
    c = unicodedata.normalize('NFC', chr(cp) + '̸')
    if len(c) == 1:
        out.append('\t0x%x: 0x%x,' % (cp, ord(c)))
out.append('}')
open('mathmldata.go', 'w', encoding='utf-8').write('\n'.join(out) + '\n')
